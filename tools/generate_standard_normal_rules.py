"""Print the checked-in positive-half standard-normal Gauss-Hermite rules."""

from __future__ import annotations

import struct
from math import sqrt, tau

import numpy as np
from scipy.special import roots_hermitenorm

ORDERS = (32, 64, 128, 256, 512, 1024, 2048)


def _bits(value: np.float64) -> int:
    return struct.unpack("<Q", struct.pack("<d", float(value)))[0]


def main() -> None:
    """Emit exact f64 bit patterns; zero-underflow weights are deliberately omitted."""
    print("#![allow(clippy::unreadable_literal)]\n")
    print("//! Generated by `uv run tools/generate_standard_normal_rules.py`.")
    print("//! `SciPy` 1.18.0 `roots_hermitenorm`, normalized by `sqrt(2*pi)`.\n")
    for order in ORDERS:
        nodes, raw_weights = roots_hermitenorm(order)
        weights = np.asarray(raw_weights / sqrt(tau), dtype=np.float64)
        positive = [
            (node, weight)
            for node, weight in zip(nodes, weights, strict=True)
            if node > 0 and weight > 0
        ]
        print(f"const ORDER_{order}: &[(f64, f64)] = &[")
        for node, weight in positive:
            print(
                "    (f64::from_bits(0x"
                f"{_bits(node):016x}), f64::from_bits(0x{_bits(weight):016x})),"
            )
        print("];\n")
    print(
        "pub(super) fn positive_nodes_and_weights(order: usize) -> Option<&'static [(f64, f64)]> {"
    )
    print("    match order {")
    for order in ORDERS:
        print(f"        {order} => Some(ORDER_{order}),")
    print("        _ => None,")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
