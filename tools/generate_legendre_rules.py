"""Print the checked-in Gauss-Legendre rules used by American pricing."""

from __future__ import annotations

import struct

import numpy as np
from scipy.special import roots_legendre

ORDERS = (5, 8, 13, 15, 21, 31, 41, 51, 61, 81, 131)


def _bits(value: np.float64) -> int:
    return struct.unpack("<Q", struct.pack("<d", float(value)))[0]


def main() -> None:
    """Emit exact f64 bit patterns with exact mirrored node and weight identities."""
    print("#![allow(clippy::unreadable_literal)]\n")
    print("//! Generated by `uv run tools/generate_legendre_rules.py`.")
    print("//! `SciPy` 1.18.0 `roots_legendre` on `[-1, 1]`.\n")
    for order in ORDERS:
        raw_nodes, raw_weights = roots_legendre(order)
        nodes = np.asarray(raw_nodes, dtype=np.float64)
        weights = np.asarray(raw_weights, dtype=np.float64)
        for index in range(order // 2):
            mirror = order - index - 1
            magnitude = np.float64((abs(nodes[index]) + abs(nodes[mirror])) / 2.0)
            weight = np.float64((weights[index] + weights[mirror]) / 2.0)
            nodes[index] = -magnitude
            nodes[mirror] = magnitude
            weights[index] = weight
            weights[mirror] = weight
        if order % 2:
            nodes[order // 2] = np.float64(0.0)
        print(f"const ORDER_{order}: &[(f64, f64)] = &[")
        for node, weight in zip(nodes, weights, strict=True):
            print(
                "    (f64::from_bits(0x"
                f"{_bits(node):016x}), f64::from_bits(0x{_bits(weight):016x})),"
            )
        print("];\n")
    print("pub(super) fn nodes_and_weights(order: usize) -> Option<&'static [(f64, f64)]> {")
    print("    match order {")
    for order in ORDERS:
        print(f"        {order} => Some(ORDER_{order}),")
    print("        _ => None,")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
